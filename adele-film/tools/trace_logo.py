"""Trace the Adele Care symbol into an SVG path so it can be drawn on and filled in code.

usage: python -I tools/trace_logo.py public/brand/symbol.png src/brandPath.ts
"""
import sys

import numpy as np
import potrace
from PIL import Image

src, dst = sys.argv[1], sys.argv[2]
im = Image.open(src).convert("RGBA")
alpha = np.array(im)[:, :, 3] > 128
ys, xs = np.nonzero(alpha)
x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
alpha = alpha[y0:y1, x0:x1]
h, w = alpha.shape

# potracer traces the False pixels, so pass the inverse to trace the symbol itself
plist = potrace.Bitmap(~alpha).trace(turdsize=20, alphamax=1.1, opticurve=True, opttolerance=0.4)
parts = []
for curve in plist:
    sx, sy = curve.start_point.x, curve.start_point.y
    d = [f"M{sx:.1f} {sy:.1f}"]
    for seg in curve.segments:
        if seg.is_corner:
            d.append(f"L{seg.c.x:.1f} {seg.c.y:.1f}L{seg.end_point.x:.1f} {seg.end_point.y:.1f}")
        else:
            d.append(
                f"C{seg.c1.x:.1f} {seg.c1.y:.1f} {seg.c2.x:.1f} {seg.c2.y:.1f} {seg.end_point.x:.1f} {seg.end_point.y:.1f}"
            )
    parts.append("".join(d) + "Z")

with open(dst, "w") as f:
    f.write("// Generated by tools/trace_logo.py from public/brand/symbol.png. Do not edit by hand.\n")
    f.write(f"export const SYMBOL_W = {w};\nexport const SYMBOL_H = {h};\n")
    f.write("export const SYMBOL_PATHS = [\n")
    for p in parts:
        f.write(f'  "{p}",\n')
    f.write("];\n")
print(f"{len(parts)} subpaths, {w}x{h}, {sum(len(p) for p in parts)} chars")
